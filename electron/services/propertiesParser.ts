import fs from 'fs';
import path from 'path';

export const DEFAULT_PROPERTIES: Record<string, string> = {
  'difficulty': 'normal',
  'gamemode': 'survival',
  'hardcore': 'false',
  'pvp': 'true',
  'white-list': 'false',
  'enforce-whitelist': 'false',
  'online-mode': 'true',
  'enable-command-block': 'true',
  'spawn-monsters': 'true',
  'spawn-animals': 'true',
  'spawn-npcs': 'true',
  'allow-nether': 'true',
  'generate-structures': 'true',
  'spawn-protection': '16',
  'max-players': '20',
  'view-distance': '10',
  'simulation-distance': '10',
  'server-port': '25565',
  'motd': 'A CraftPulse Minecraft Server',
  'level-seed': '',
  'level-name': 'world'
};

export class PropertiesParser {
  /**
   * Parse a server.properties file into a JavaScript object
   */
  static parse(filePath: string): Record<string, any> {
    if (!fs.existsSync(filePath)) {
      return { ...DEFAULT_PROPERTIES };
    }

    const content = fs.readFileSync(filePath, 'utf-8');
    const lines = content.split(/\r?\n/);
    const properties: Record<string, any> = { ...DEFAULT_PROPERTIES };

    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#') || trimmed.startsWith('!')) {
        continue;
      }
      const separatorIndex = trimmed.indexOf('=');
      if (separatorIndex === -1) continue;

      const key = trimmed.substring(0, separatorIndex).trim();
      const rawValue = trimmed.substring(separatorIndex + 1).trim();

      // Convert typed values
      if (rawValue === 'true') properties[key] = true;
      else if (rawValue === 'false') properties[key] = false;
      else if (!isNaN(Number(rawValue)) && rawValue !== '') properties[key] = Number(rawValue);
      else properties[key] = rawValue;
    }

    return properties;
  }

  /**
   * Write properties back to server.properties, preserving comments
   */
  static save(filePath: string, updatedProps: Record<string, any>): void {
    let existingLines: string[] = [];
    if (fs.existsSync(filePath)) {
      existingLines = fs.readFileSync(filePath, 'utf-8').split(/\r?\n/);
    } else {
      existingLines = ['# Minecraft server properties generated by CraftPulse', `# ${new Date().toISOString()}`];
    }

    const writtenKeys = new Set<string>();
    const newLines: string[] = [];

    for (const line of existingLines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#') || trimmed.startsWith('!')) {
        newLines.push(line);
        continue;
      }

      const separatorIndex = trimmed.indexOf('=');
      if (separatorIndex !== -1) {
        const key = trimmed.substring(0, separatorIndex).trim();
        if (key in updatedProps) {
          const val = updatedProps[key] !== undefined ? String(updatedProps[key]) : '';
          newLines.push(`${key}=${val}`);
          writtenKeys.add(key);
        } else {
          newLines.push(line);
        }
      } else {
        newLines.push(line);
      }
    }

    // Append any keys that weren't in the original file
    for (const [key, val] of Object.entries(updatedProps)) {
      if (!writtenKeys.has(key) && val !== undefined) {
        newLines.push(`${key}=${String(val)}`);
      }
    }

    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, newLines.join('\n'), 'utf-8');
  }
}
